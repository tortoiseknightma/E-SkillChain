def test_phase_summary_has_stable_anchor_and_is_frozen() -> None:
    phase = PhaseSummary(number=3, title="Review", completed_tasks=1, total_tasks=2)

    assert phase.anchor == "phase-3"
    try:
        phase.number = 4
    except FrozenInstanceError:
        pass
    else:
        raise AssertionError("expected FrozenInstanceError")


def test_plan_summary_is_frozen() -> None:
    summary = PlanSummary(
        phases=(), completed_tasks=0, total_tasks=0, current_phase_number=None
    )

    try:
        summary.total_tasks = 1
    except FrozenInstanceError:
        pass
