def test_parse_plan_summarizes_each_phase_and_global_tasks() -> None:
    summary = parse_plan(SAMPLE_PLAN)
    assert summary.total_tasks == 5
    assert summary.completed_tasks == 3
    assert [
        (phase.number, phase.completed_tasks, phase.total_tasks)
        for phase in summary.phases
    ] == [(0, 2, 2), (1, 1, 2), (2, 0, 1)]
    assert summary.current_phase_number == 1


